const AR = {
  explains: /दोनों सही हैं,? (और|तथा) \(R\), \(A\) की सही व्याख्या है/,
  not: /दोनों सही हैं, (पर|परन्तु) \(R\), \(A\) की सही व्याख्या नहीं/,
  aTrue: /^\(A\) सही है, (पर|परन्तु) \(R\) (गलत|ग़लत)/,
  aFalse: /^\(A\) (गलत|ग़लत) है, (पर|परन्तु) \(R\) सही/,
};

function ar(id, { A, R, kind, explanation }) {
  const q = get(id);
  let text = q.question;
  if (A) text = text.replace(/कथन \(A\): .*/, `कथन (A): ${A}`);
  if (R) text = text.replace(/कारण \(R\): .*/, `कारण (R): ${R}`);
  if (text === q.question) throw new Error(`${id}: पाठ नहीं बदला`);
  update[id] = { question: text, answer: idx(q, AR[kind]), explanation, _why: 'A-R उत्तर विविध' };
}

