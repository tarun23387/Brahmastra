function push(subject, question, options, explanation, extra = {}) {
  const prefix = subject === 'ca' ? 'roaro-ca' : 'roaro-rq';
  const id = `${prefix}-${String(++count[subject]).padStart(3, '0')}`;
  let opts = options;
  let answer = 0;
  if (extra.match) {
    const r = matchOptions(extra.correct, rnd);
    opts = r.options;
    answer = r.answer;
  } else if (!extra.fixed) {
    // पहला सही; बाक़ी फेंटकर सही को सबसे कम भरी जगह पर रखिए
    const correct = options[0];
    const others = options.slice(1);
    for (let i = others.length - 1; i > 0; i--) {
      const j = Math.floor(rnd() * (i + 1));
      [others[i], others[j]] = [others[j], others[i]];
    }
    const min = Math.min(...placed);
    const c = [0, 1, 2, 3].filter((i) => placed[i] === min);
    answer = c[Math.floor(rnd() * c.length)];
    others.splice(answer, 0, correct);
    opts = others;
  } else {
    answer = extra.answer;
  }
  placed[answer]++;
  rows.push({
    id,
    subject,
    exams: ['roaro'],
    question,
    options: opts,
    answer,
    explanation,
    difficulty: extra.difficulty || 'moderate',
    ...(extra.match ? { match: extra.match } : {}),
  });
}

