// ── 2. कथन वाले ────────────────────────────────────────

function st(id, lines, answer, explanation) {
  const q = get(id);
  let text = q.question;
  for (const [n, s] of Object.entries(lines)) {
    const re = new RegExp(`^${n}\\. .*$`, 'm');
    if (!re.test(text)) throw new Error(`${id}: कथन ${n} नहीं मिला`);
    text = text.replace(re, `${n}. ${s}`);
  }
  const a = q.options.indexOf(answer);
  if (a < 0) throw new Error(`${id}: विकल्प '${answer}' नहीं है`);
  update[id] = { question: text, answer: a, explanation, _why: 'कथन-उत्तर विविध' };
}

