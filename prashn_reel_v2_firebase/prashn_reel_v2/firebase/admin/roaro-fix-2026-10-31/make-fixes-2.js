/** id से बीज: make.js और यह लिपि एक ही प्रश्न के लिए एक ही कूट बनाएँ */
function seeded(id) {
  let s = 0;
  for (const ch of id) s = (s * 31 + ch.charCodeAt(0)) % 2147483647;
  return () => ((s = (s * 1103515245 + 12345) % 2147483648) / 2147483648);
}

// ── 1. सूची-मिलान ──
{
  const isCode = (o) => /^A-\d, B-\d, C-\d, D-\d$/.test(o);
  const list = bank.filter(
    (q) => q.papers.some((p) => p.startsWith('roaro')) && !q.year && q.options.every(isCode)
  );
  let strict = 0;
  for (const q of list) {
    const correct = q.options[q.answer].match(/\d/g).map(Number);
    const r = matchOptions(correct, seeded(q.id));
    if (r.strict) strict++;
    update[q.id] = { options: r.options, answer: r.answer, _why: 'सूची-मिलान कूट अंदाज़े से न निकलें' };
  }
  console.log(`सूची-मिलान: ${list.length} के कूट नए (${strict} पूरी शर्त वाले)`);
}

// ── 2. सीधे प्रश्न: पहला विकल्प सही; जगह बीज से ──
function put(id, question, options, explanation) {
  const q = byId.get(id);
  if (!q) throw new Error(`नहीं मिला: ${id}`);
  const rnd = seeded(id + '#');
  const correct = options[0];
  const others = options.slice(1);
  for (let i = others.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [others[i], others[j]] = [others[j], others[i]];
  }
  const at = Math.floor(rnd() * 4);
  others.splice(at, 0, correct);
  const u = { options: others, answer: at, _why: 'ग़लत विकल्प RO/ARO स्तर के' };
  if (question) u.question = question;
  if (explanation) u.explanation = explanation;
  update[id] = u;
}

/** सिर्फ़ विकल्पों का पाठ बदलना, जगह वही (कोष्ठक/लंबाई का संकेत हटाना) */
function trim(id, from, to, extra = {}) {
  const q = byId.get(id);
  const options = q.options.map((o) => (o === from ? to : extra[o] ?? o));
  if (!options.includes(to)) throw new Error(`${id}: '${from}' नहीं मिला`);
  update[id] = { options, answer: q.answer, _why: 'सही विकल्प पर कोष्ठक/लंबाई का संकेत हटाया' };
}

