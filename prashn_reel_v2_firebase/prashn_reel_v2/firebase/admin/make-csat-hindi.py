# सही उत्तर चारों जगह बराबर — लिखते समय ज़्यादातर (ब) पर चला गया था, और
# छात्र ऐसा पैटर्न जल्दी पकड़ लेता है. सही विकल्प को लक्ष्य वाली जगह से
# अदला-बदली कर देते हैं. "उपर्युक्त…" वाले प्रश्न नहीं छूते — वह विकल्प
# हमेशा आख़िर में ही रहना चाहिए.
slot = 0
for item in Q:
    if any("उपर्युक्त" in o for o in item["options"]):
        continue
    target = slot % 4
    slot += 1
    o, a = item["options"], item["answer"]
    o[a], o[target] = o[target], o[a]
    item["answer"] = target

for i, item in enumerate(Q, 1):
    item["id"] = f"csat-hi-{i:03d}"

# दोहराव की जाँच — एक ही प्रश्न दो बार न जाए
seen = set()
for item in Q:
    key = item["question"] + "|" + "/".join(item["options"])  # एक-सा प्रश्न-वाक्य चल जाता है, विकल्प अलग हों
    assert key not in seen, key
    seen.add(key)

