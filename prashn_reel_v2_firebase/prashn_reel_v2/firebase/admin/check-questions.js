/**
 * प्रश्न फ़ाइल की सफ़ाई-जाँच — Firestore में डालने से पहले.
 *
 *   node check-questions.js pet-arth-100.json
 *
 * `import.js` ढाँचा जाँचता है (4 विकल्प, answer 0-3, विषय पहचाना हुआ).
 * यह लिपि वे गड़बड़ियाँ पकड़ती है जो ढाँचे से नहीं पकड़ी जातीं पर छात्र
 * को दिखती हैं:
 *
 *   • बाहरी वर्ण   — देवनागरी के बीच अरबी/चीनी अक्षर घुस जाना. एक बार
 *                    'अनुच्छेद' में 'द' की जगह अरबी 'د' चला गया था.
 *   • मिली-जुली लिपि — 'समिti' जैसा शब्द, जहाँ बीच में कीबोर्ड बदल गया.
 *   • अधूरा वाक्य  — प्रश्न के अंत में प्रश्नवाचक चिह्न न होना.
 *   • दोहराव       — एक ही प्रश्न फ़ाइल में दो बार.
 *   • बिना व्याख्या — जिनसे छात्र सीख नहीं पाएगा.
 *
 * सही उत्तर की जगह का बँटवारा `shuffle-answers.js` सँभालता है; यहाँ
 * सिर्फ़ गिनकर बता देते हैं.
 */
const fs = require('fs');

const file = process.argv[2];
if (!file) {
  console.error('usage: node check-questions.js <file.json>');
  process.exit(1);
}

const rows = JSON.parse(fs.readFileSync(file, 'utf8'));

// देवनागरी, लातिनी, अंक, आम विराम चिह्न और गणित के चिह्न —
// इनके बाहर कुछ भी संदिग्ध है.
//
// गणित के प्रश्नों में √, π, −, ², ³ जैसे चिह्न ज़रूरी हैं; इन्हें रोकने
// पर हर गणित बैच झूठी चेतावनी देने लगता था.
const ALLOWED = new RegExp(
  '^[\\u0900-\\u097F\\u0020-\\u007E\\u2018\\u2019\\u201C\\u201D\\u2013\\u2014' +
    '\\u00B0\\u00D7\\u00F7\\u00A0\\u20B9\\u2026\\n\\t' +
    '\\u2212\\u221A\\u03C0\\u00B2\\u00B3\\u2248\\u2260\\u2264\\u2265' +
    '\\u00BC\\u00BD\\u00BE\\u2153\\u2154\\u215B\\u2192\\u2194' +
    '\\u2070\\u00B9\\u2074-\\u2079\\u207F\\u00B1\\u2080-\\u2089]*$'
);

// एक ही शब्द में देवनागरी और लातिनी सटे हुए.
//
// दो या अधिक लातिनी अक्षर ही पकड़ते हैं — 'समिti' जैसी असली गड़बड़ी.
// अकेला अक्षर छोड़ देते हैं, क्योंकि गणित में 'nवाँ पद' और 'xवाँ भाग'
// जायज़ हैं और उन पर झूठी चेतावनी आती थी.
// विराम चिह्न (। ॥) इस जाँच से बाहर हैं. अंग्रेज़ी विषय की व्याख्याएँ
// 'past participle।' की तरह ख़त्म होती हैं — वह मिली-जुली लिपि नहीं,
// सामान्य लेखन है. सिर्फ़ देवनागरी *अक्षरों* से सटा लातिनी पकड़ना है.
const MIXED = /[ऀ-ॣ०-ॿ][A-Za-z]{2,}|[A-Za-z]{2,}[ऀ-ॣ०-ॿ]/;

let problems = 0;
const say = (i, msg, q) => {
  problems++;
  console.log(
    `  #${i + 1}  ${msg}\n       ${q.question.replace(/\n/g, ' ').slice(0, 60)}`
  );
};

const seen = new Map();
const spread = [0, 0, 0, 0];

rows.forEach((q, i) => {
  const texts = [q.question, ...q.options, q.explanation || ''];

  for (const t of texts) {
    if (!ALLOWED.test(t)) {
      const bad = [...t].filter((ch) => !ALLOWED.test(ch));
      say(i, `बाहरी वर्ण: ${JSON.stringify(bad.join(''))}`, q);
      break;
    }
  }

  for (const t of texts) {
    const m = t.match(MIXED);
    if (m) {
      say(i, `देवनागरी में लातिनी अक्षर: ${JSON.stringify(m[0])}`, q);
      break;
    }
  }

  // प्रश्नवाचक चिह्न कहीं भी हो — कुछ प्रश्न '...क्या होगा? (π = 22/7)'
  // की तरह कोष्ठक पर ख़त्म होते हैं, वे ग़लत नहीं हैं.
  // प्रश्न का वाक्य पूरा हुआ या नहीं.
  //
  // हर प्रश्न में '?' ज़रूरी नहीं — 'Choose the correct form.' और
  // 'शुद्ध शब्द छाँटिए।' जैसे आदेश-वाक्य भी पूरे प्रश्न हैं. असल में
  // पकड़ना यह है कि वाक्य बीच में कटा तो नहीं. इसलिए कोई भी अंतिम
  // विराम चिह्न चलेगा.
  // अंत में उद्धरण ('...'), कोष्ठक (π = 22/7) या सूची (3, 5, 7, 9)
  // भी चलती है — ये सब पूरे प्रश्न हैं.
  //
  // डैश (—) भी चलेगा. पूरे बैंक में अधूरे वाक्य वाले प्रश्न — '...का
  // मान है —' — उसी से ख़त्म होते हैं. वह शैली है, कटा वाक्य नहीं;
  // उसे पकड़ने से हर बैच पर दर्जनों झूठी चेतावनियाँ आती थीं.
  if (!/[?.।:'"’”)\d—–]\s*$/.test(q.question.trim()) && !q.question.includes('\n')) {
    say(i, 'प्रश्न का वाक्य अधूरा लगता है (अंत में विराम चिह्न नहीं)', q);
  }

  if (!q.explanation || !q.explanation.trim()) say(i, 'व्याख्या नहीं है', q);

  const key = q.question.trim();
  if (seen.has(key)) say(i, `दोहराव — #${seen.get(key) + 1} जैसा ही`, q);
  else seen.set(key, i);

  if (Number.isInteger(q.answer) && q.answer >= 0 && q.answer < 4) {
    spread[q.answer]++;
  }
});

console.log(`\nकुल ${rows.length} प्रश्न`);
console.log(`सही उत्तर की जगह (अ/ब/स/द): ${spread.join(' / ')}`);
console.log(
  problems === 0 ? '✅ कोई गड़बड़ नहीं मिली.' : `⚠️  ${problems} जगह ध्यान चाहिए.`
);
process.exit(problems === 0 ? 0 : 1);
