// ── 3. कथन वाले ──
function st(id, lines, answer, explanation) {
  const q = get(id);
  let text = q.question;
  for (const [n, s] of Object.entries(lines)) {
    const re = new RegExp(`^(\\s*)${n}\\. .*$`, 'm');
    if (!re.test(text)) throw new Error(`${id}: कथन ${n} नहीं मिला`);
    text = text.replace(re, `$1${n}. ${s}`);
  }
  const a = q.options.findIndex((o) => o.trim() === answer);
  if (a < 0) throw new Error(`${id}: विकल्प '${answer}' नहीं है`);
  const u = { answer: a, explanation, _why: 'कथन-उत्तर विविध / तथ्य सुधार' };
  if (text !== q.question) u.question = text;
  update[id] = u;
}

