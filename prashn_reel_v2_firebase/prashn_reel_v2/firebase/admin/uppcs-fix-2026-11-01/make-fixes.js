function seeded(id) {
  let s = 7;
  for (const ch of id) s = (s * 31 + ch.charCodeAt(0)) % 2147483647;
  return () => ((s = (s * 1103515245 + 12345) % 2147483648) / 2147483648);
}

// ── 1. सूची-मिलान ──
{
  const list = bank.filter((q) => q.paper === 'uppcs-gs1' && !q.year && q.match && /सुमेलित कीजिए/.test(q.question));
  let n = 0;
  for (const q of list) {
    const code = String(q.options[q.answer]).match(/\d/g)?.map(Number);
    if (!code || code.length !== 4) continue;
    const strip = (s) => s.replace(/^\s*\d+\.\s*/, '');
    const pairs = code.map((k, i) => [q.match.left[i], strip(q.match.right[k - 1])]);
    const rnd = seeded(q.id);
    // नई सूची-II: पहचान वाला (1,2,3,4) क्रम नहीं
    let order;
    do {
      order = [0, 1, 2, 3];
      for (let i = 3; i > 0; i--) {
        const j = Math.floor(rnd() * (i + 1));
        [order[i], order[j]] = [order[j], order[i]];
      }
    } while (order.every((v, i) => v === i));
    const right = order.map((k, i) => `${i + 1}. ${pairs[k][1]}`);
    const correct = pairs.map((_, i) => order.indexOf(i) + 1);
    const r = matchOptions(correct, rnd);
    const options = r.options.map((o) => o.replace(/[A-D]-/g, ''));
    let text = q.question;
    q.match.right.forEach((line, i) => {
      if (!text.includes(line)) throw new Error(`${q.id}: सूची-II की पंक्ति नहीं मिली`);
      text = text.replace(line, `\u0000${i}`);
    });
    right.forEach((line, i) => (text = text.replace(`\u0000${i}`, line)));
    const u = { question: text, match: { ...q.match, right }, options, answer: r.answer, _why: 'सूची-II उसी क्रम में थी (उत्तर 1, 2, 3, 4)' };
    if (/\d,\s*\d,\s*\d,\s*\d|[A-D]\s*[-–]\s*\d|कूट|\(\d\)/.test(q.explanation)) {
      u.explanation = 'सही सुमेल: ' + pairs.map(([l, rr]) => `${l.replace(/^[A-D]\.\s*/, '')} – ${rr}`).join('; ') + '।';
    }
    update[q.id] = u;
    n++;
  }
  console.log(`सूची-मिलान: ${n} दोबारा बने`);
}

