// ── 1ख. हाथ से बराबर विकल्प (पहला सही; जगह बीज से) ──
function put(id, options, explanation, question) {
  const q = byId.get(id);
  if (!q) throw new Error(`नहीं मिला: ${id}`);
  const rnd = seeded(id);
  const correct = options[0];
  const others = options.slice(1);
  for (let i = others.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [others[i], others[j]] = [others[j], others[i]];
  }
  const at = Math.floor(rnd() * 4);
  others.splice(at, 0, correct);
  const u = { ...(update[id] ?? {}), options: others, answer: at, _why: 'विकल्प बराबर, ग़लत विकल्प उसी परिवार के' };
  if (explanation) u.explanation = explanation;
  if (question) u.question = question;
  update[id] = u;
}

