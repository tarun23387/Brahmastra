/** सूची-मिलान: pairs = [[बायाँ, दायाँ], …] सही जोड़ियाँ; order = सूची-II का क्रम (दाएँ के सूचकांक) */
function M(s, lt, rt, pairs, order, e) {
  const left = pairs.map((p, i) => `${'ABCD'[i]}. ${p[0]}`);
  const right = order.map((k, i) => `${i + 1}. ${pairs[k][1]}`);
  const correct = pairs.map((_, i) => order.indexOf(i) + 1);
  push(s, [MATCH, lt, ...left, rt, ...right].join('\n'), null, e, {
    match: { intro: MATCH, leftTitle: lt, rightTitle: rt, left, right },
    correct,
  });
}
