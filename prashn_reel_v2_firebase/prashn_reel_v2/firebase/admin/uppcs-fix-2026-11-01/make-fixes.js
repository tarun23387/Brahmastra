const AR = {
  explains: /दोनों सही हैं,? (और|तथा) \(R\), \(A\) की सही व्याख्या है/,
  not: /दोनों सही हैं,? (पर|परन्तु|किंतु) \(R\), \(A\) की सही व्याख्या नहीं/,
  aTrue: /^\(A\) सही है,? (पर|परन्तु|किंतु) \(R\) (गलत|ग़लत)/,
  aFalse: /^\(A\) (गलत|ग़लत) है,? (पर|परन्तु|किंतु) \(R\) सही/,
};
const idx = (q, re) => {
  const i = q.options.findIndex((o) => re.test(o.replace(/़/g, '').trim()));
  if (i < 0) throw new Error(`${q.id}: विकल्प नहीं मिला ${re}`);
  return i;
};
function ar(id, { A, R, kind, explanation }) {
  const q = get(id);
  let text = q.question;
  if (A) text = text.replace(/कथन \(A\): [^\n]*?(?= कारण \(R\)|\n|$)/, `कथन (A): ${A}`);
  if (R) text = text.replace(/कारण \(R\): [^\n]*/, `कारण (R): ${R}`);
  const u = { answer: idx(q, AR[kind]), explanation, _why: 'A-R उत्तर विविध' };
  if (text !== q.question) u.question = text;
  update[id] = u;
}

