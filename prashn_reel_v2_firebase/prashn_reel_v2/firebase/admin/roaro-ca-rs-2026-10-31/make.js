function verify() {
  const pos = (c) => c.charCodeAt(0) - 64;
  const chk = (ok, msg) => { if (!ok) throw new Error('जाँच विफल: ' + msg); };
  chk(47 * 2 + 1 === 95, 'श्रृंखला 1');
  chk(121 * 3 + 1 === 364, 'श्रृंखला 2');
  chk(6 * 6 - 1 === 35 && 7 * 7 - 1 === 48, 'ग़लत पद');
  chk(90 * 3.5 === 315, '×3.5');
  chk([...'GOLD'].map((c, i) => String.fromCharCode(64 + pos(c) + i + 1)).join('') === 'HQOH', 'GOLD');
  chk([...'IRON'].map((c, i) => String.fromCharCode(64 + pos(c) + i + 1)).join('') === 'JTRR', 'IRON');
  chk(2 + 3 + 4 + 5 + 6 + 7 === 27, 'B E I N T');
  chk(Math.hypot(6, 8) === 10 && Math.hypot(12, 5) === 13, 'दूरी');
  chk(18 + 6 - 1 === 23 && 23 - 9 + 1 === 15, 'कतार');
  chk(new Date(Date.UTC(1947, 7, 15)).getUTCDay() === 5, '15 अगस्त 1947 शुक्रवार');
  chk(new Date(Date.UTC(2027, 0, 1)).getUTCDay() === 5 && new Date(Date.UTC(2028, 0, 1)).getUTCDay() === 6, '2027/2028');
  chk(Math.abs(30 * 7 - 5.5 * 20) === 100, '7:20');
  chk(Math.abs(90 / 5.5 - (16 + 4 / 11)) < 1e-9, 'सुइयाँ मिलना');
  chk(16 / 4 * 5 + 8 - 6 === 22, 'चिह्न');
  chk(420 / 21 * 3 === 60, 'सिक्के');
  chk(4 * 8 + 16 === 2 * (8 + 16), 'आयु');
  chk(35 + 30 - (60 - 10) === 15, 'वेन');
  chk(26 - 10 + 1 - 4 === 13, 'वर्णमाला');
  const letters = (w) => [...w].reduce((m, c) => ((m[c] = (m[c] || 0) + 1), m), {});
  const can = (w) => Object.entries(letters(w)).every(([c, n]) => (letters('PARLIAMENT')[c] || 0) >= n);
  chk(!can('PARTNER') && can('PLANET') && can('MENTAL') && can('TRAMPLE'), 'PARLIAMENT');
}
