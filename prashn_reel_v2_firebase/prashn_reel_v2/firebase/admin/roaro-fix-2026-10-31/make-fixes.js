let seed = 20261031;
const rnd = () => ((seed = (seed * 1103515245 + 12345) % 2147483648) / 2147483648);

// ── 3. सूची-मिलान के दोहराए कोड ──────────────────────────
{
  const OVER = ['A-4, B-3, C-2, D-1', 'A-3, B-4, C-1, D-2'];
  const perms = [];
  const perm = (a, p = []) => (a.length ? a.forEach((x, i) => perm([...a.slice(0, i), ...a.slice(i + 1)], [...p, x])) : perms.push(p));
  perm([1, 2, 3, 4]);
  const code = (p) => p.map((n, i) => `${'ABCD'[i]}-${n}`).join(', ');
  const roaroNew = bank.filter((q) => q.papers.some((p) => p.startsWith('roaro')) && !q.year && q.match);
  const used = {};
  for (const q of roaroNew) used[q.options[q.answer]] = (used[q.options[q.answer]] || 0) + 1;
  const pool = perms.filter((p) => !OVER.includes(code(p)) && p.some((n, i) => n !== i + 1));
  let changed = 0;
  for (const target of OVER) {
    const list = roaroNew.filter((q) => q.options[q.answer] === target && !update[q.id]);
    for (const q of list.slice(4)) {
      if (/[A-D]-[1-4]|\b[1-4]\./.test(q.explanation)) continue; // व्याख्या क्रमांक से बुलाती हो तो छोड़िए
      const old = target.match(/\d/g).map(Number);
      const items = old.map((n) => q.match.right[n - 1].replace(/^\d+\.\s*/, '')); // A..D की सही जोड़ी
      pool.sort((a, b) => (used[code(a)] || 0) - (used[code(b)] || 0) || rnd() - 0.5);
      const p = pool[0];
      used[code(p)] = (used[code(p)] || 0) + 1;
      const right = [];
      p.forEach((n, i) => (right[n - 1] = `${n}. ${items[i]}`));
      const sw = (i, j) => { const c = [...p]; [c[i], c[j]] = [c[j], c[i]]; return code(c); };
      const distract = [...new Set([sw(0, 1), sw(2, 3), sw(1, 2), sw(0, 3)])].filter((c) => c !== code(p)).slice(0, 3);
      const options = [...distract];
      const at = Math.floor(rnd() * 4);
      options.splice(at, 0, code(p));
      let text = q.question;
      q.match.right.forEach((line, i) => {
        if (!text.includes(line)) throw new Error(`${q.id}: सूची-II की पंक्ति नहीं मिली`);
        text = text.replace(line, `\u0000${i}`);
      });
      right.forEach((line, i) => (text = text.replace(`\u0000${i}`, line)));
      update[q.id] = { question: text, match: { ...q.match, right }, options, answer: at, _why: 'दोहराया सूची-मिलान कोड' };
      changed++;
    }
  }
  console.log(`सूची-मिलान: ${changed} के कोड बदले`);
}

// ── 4. imp-* / seed-* के विकल्प फेंटना ────────────────────
{
  const ORDER_SENSITIVE = /(तीनों|चारों|दोनों|सभी|उपरोक्त|इनमें से कोई|कोई नहीं|उपर्युक्त|^केवल|^\(A\)|^[IVX]+[,.]|^A-\d|^\d,)/;
  const NAMES_OPTION = /विकल्प\s*\(?[A-Dअबसद1-4]\)?|option\s*\(?[a-d]\)?/i;
  const list = bank.filter(
    (q) => /^(imp|seed)-/.test(q.id) && q.papers.some((p) => p.startsWith('roaro')) && !update[q.id]
  );
  const placed = [0, 0, 0, 0];
  let skipped = 0;
  const todo = [];
  for (const q of list) {
    if (q.options.some((o) => ORDER_SENSITIVE.test(o)) || NAMES_OPTION.test(q.explanation) || q.options.length !== 4) {
      placed[q.answer]++;
      skipped++;
    } else todo.push(q);
  }
  for (const q of todo) {
    const correct = q.options[q.answer];
    const others = q.options.filter((_, i) => i !== q.answer);
    for (let i = others.length - 1; i > 0; i--) {
      const j = Math.floor(rnd() * (i + 1));
      [others[i], others[j]] = [others[j], others[i]];
    }
    const min = Math.min(...placed);
    const cands = [0, 1, 2, 3].filter((i) => placed[i] === min);
    const at = cands[Math.floor(rnd() * cands.length)];
    placed[at]++;
    others.splice(at, 0, correct);
    if (at !== q.answer || others.join('\u0001') !== q.options.join('\u0001')) {
      update[q.id] = { options: others, answer: at, _why: 'उत्तर (B) पर अधिक, (D) पर लगभग शून्य था' };
    }
  }
  console.log(`imp/seed: ${todo.length} फेंटे, ${skipped} क्रम-संवेदी छोड़े, जगह ${placed.join(' / ')}`);
}

